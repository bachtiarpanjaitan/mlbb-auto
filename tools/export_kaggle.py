def dataset_info() -> dict:
    """Return dataset summary."""
    from collections import Counter

    lbl_dir = DATASET_DIR / "labels" / "train"
    img_dir = DATASET_DIR / "images" / "train"
    val_img = DATASET_DIR / "images" / "val"

    labels = list(lbl_dir.glob("*.txt"))
    c = Counter()
    for f in labels:
        for line in f.read_text().strip().split("\n"):
            parts = line.strip().split()
            if parts:
                c[int(parts[0])] += 1

    return {
        "train_imgs": len(list(img_dir.glob("*.png"))),
        "train_lbls": len(labels),
        "val_imgs": len(list(val_img.glob("*.png"))),
        "annotations": sum(c.values()),
        "classes": dict(sorted(c.items())),
    }


