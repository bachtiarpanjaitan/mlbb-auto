def create_zip(path: Path):
    """Zip dataset for Kaggle upload."""
    zip_path = path / "hero_detector.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for folder in ["images", "labels"]:
            for split in ["train", "val"]:
                dir_path = DATASET_DIR / folder / split
                if not dir_path.exists():
                    continue
                for f in sorted(dir_path.iterdir()):
                    z.write(f, f"{folder}/{split}/{f.name}")
        # data.yaml
        data_yaml = DATASET_DIR / "data.yaml"
        if data_yaml.exists():
            z.write(data_yaml, "data.yaml")

    size_mb = zip_path.stat().st_size / (1024 * 1024)
    print(f"  ✅ Dataset zip: {zip_path} ({size_mb:.1f} MB)")
    return zip_path


